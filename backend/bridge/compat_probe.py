"""Compat probe: launch every manifest'd provider CLI under the PTY adapter and record what really happens.
Generates COMPAT.md from evidence only. Sends NO input; kills each session after --seconds.

  python -m bridge.compat_probe [--seconds 8] [--out COMPAT.md]
"""
import argparse
import asyncio
import re
import time
from datetime import datetime
from pathlib import Path

from bridge.manifests import load_manifests, scrubbed_env
from bridge.pty_session import PtySession

ANSI = re.compile(r"\x1b\[[0-?]*[ -/]*[@-~]|\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)|\x1b[()][A-Za-z0-9]|\x1b[=>]")


def clean(s: str) -> str:
    return re.sub(r"\s+", " ", ANSI.sub("", s)).strip()


async def probe_one(m, seconds: float, cwd: Path):
    row = {"id": m.id, "label": m.label, "installed": m.available, "path": m.resolved or "-"}
    if not m.available:
        return {**row, "starts": False, "first_output_ms": None, "alive_after": False, "bytes": 0, "sample": "", "note": "not installed"}
    t0 = time.perf_counter()
    try:
        s = PtySession.spawn(m.argv(), env=scrubbed_env(m), cwd=str(cwd), cols=120, rows=30)
    except Exception as e:
        return {**row, "starts": False, "first_output_ms": None, "alive_after": False, "bytes": 0, "sample": "", "note": f"spawn failed: {e}"}
    first, total, text = None, 0, ""
    deadline = t0 + seconds
    while time.perf_counter() < deadline:
        try:
            chunk = await asyncio.wait_for(s.queue.get(), 0.25)
        except asyncio.TimeoutError:
            continue
        if chunk is None:
            break
        if first is None:
            first = (time.perf_counter() - t0) * 1000
        total += len(chunk)
        text += chunk
        # A real terminal (xterm.js in the browser) answers these queries; a headless probe must too, or TUIs stall.
        if "\x1b[6n" in chunk:
            s.write("\x1b[1;1R")
        if re.search(r"\x1b\[0?c", chunk) or "\x1b[>0c" in chunk:
            s.write("\x1b[?1;2c")
    alive = s.alive()
    s.close()
    sample = clean(text)[:110]
    return {**row, "starts": bool(sample) or first is not None, "first_output_ms": None if first is None else round(first),
            "alive_after": alive, "bytes": total, "sample": sample,
            "note": "" if first is not None else ("exited without output" if not alive else "no output within window")}


async def main(seconds: float, out: Path):
    cwd = Path("./bridge_workdir").resolve()
    cwd.mkdir(exist_ok=True)
    rows = []
    for m in load_manifests().values():
        rows.append(await probe_one(m, seconds, cwd))
        r = rows[-1]
        print(f"{r['id']:9} installed={r['installed']!s:5} starts={r['starts']!s:5} first={r['first_output_ms']}ms alive={r['alive_after']!s:5} {r['note']}", flush=True)
    lines = [f"# Provider compatibility (measured {datetime.now():%Y-%m-%d %H:%M})", "",
             "Generated by `python -m bridge.compat_probe` on this machine. Tier 0 = universal PTY adapter. A provider is",
             f"**certified for Tier 0** only if it is installed, produces output under ConPTY, and stays alive for the {seconds:.0f}s window.",
             "The probe answers terminal cursor/device queries like a real terminal would (a browser xterm does this automatically).",
             "Structured (Tier 1) support is NOT claimed here; it is assessed per provider in later phases.", "",
             "| Provider | Installed | Output under PTY | First output | Alive after | Tier 0 | First screen text (sanitized) |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        ok = r["installed"] and r["starts"] and r["alive_after"]
        lines.append(f"| {r['label']} (`{r['id']}`) | {'yes' if r['installed'] else 'no'} | {'yes' if r['starts'] else 'no'} | "
                     f"{'-' if r['first_output_ms'] is None else str(r['first_output_ms']) + ' ms'} | {'yes' if r['alive_after'] else 'no'} | "
                     f"{'**PASS**' if ok else 'FAIL'} | {(r['sample'] or r['note']).replace('|', '/')} |")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--seconds", type=float, default=12)
    ap.add_argument("--out", default="COMPAT.md")
    a = ap.parse_args()
    asyncio.run(main(a.seconds, Path(a.out)))
