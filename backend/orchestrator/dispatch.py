"""dispatch: run the three agents CONCURRENTLY (asyncio.gather), then branch/commit/PR/review each,
and open one approval request per PR. Also holds approve/reject - approve is the only merge path."""
from __future__ import annotations

import asyncio
import time
from datetime import datetime, timezone
from typing import Dict, List, Optional

from pydantic import BaseModel

from agents.base import LLMAgent
from events import EventBus
from models import (AgentRole, ApprovalRequest, ApprovalStatus, Contract, EventType, Task, TaskStatus)
from orchestrator.contract import assert_frozen
from orchestrator.guard import validate_ownership
from pipeline.github import GitHubPort
from pipeline.review import review
from state import State


class AgentRun(BaseModel):
    role: AgentRole
    status: str                       # ok | blocked | failed
    agent_elapsed_s: float = 0.0      # LLM generation time inside the agent
    total_elapsed_s: float = 0.0      # generation + branch + commit + PR + review
    branch: Optional[str] = None
    commit_sha: Optional[str] = None
    author: Optional[str] = None
    pr_url: Optional[str] = None
    approval_id: Optional[str] = None
    review_summary: str = ""
    error: Optional[str] = None


class DispatchReport(BaseModel):
    feature_id: str
    wall_s: float
    serial_s: float                   # sum of per-agent total times = what a serial run would cost
    speedup: float
    runs: List[AgentRun]

    def table(self) -> str:
        rows = [f"{'agent':9} {'status':8} {'agent_s':>8} {'total_s':>8}  author / PR"]
        for r in self.runs:
            rows.append(f"{r.role.value:9} {r.status:8} {r.agent_elapsed_s:8.2f} {r.total_elapsed_s:8.2f}  "
                        f"{r.author or '-'} {r.pr_url or r.error or ''}")
        rows.append(f"WALL-CLOCK {self.wall_s:.2f}s   SERIAL-EQUIVALENT {self.serial_s:.2f}s   SPEEDUP x{self.speedup:.2f}")
        return "\n".join(rows)


async def dispatch_feature(*, feature_id: str, contract: Contract, tasks: List[Task],
                           agents: Dict[AgentRole, LLMAgent], github: GitHubPort, state: State,
                           bus: EventBus) -> DispatchReport:
    validate_ownership(tasks)                      # re-assert isolation immediately before work starts
    assert_frozen(contract)
    contract_files = {
        f"contracts/{contract.name}_openapi.yaml": contract.openapi_yaml,
        f"contracts/{contract.name}_types.ts": contract.ts_types,
    }

    async def run_one(task: Task) -> AgentRun:
        agent = agents[task.role]
        t0 = time.perf_counter()
        run = AgentRun(role=task.role, status="failed")
        rid = dict(feature_id=feature_id, agent=task.role)
        try:
            result = await agent.run(task, contract)
            run.agent_elapsed_s = time.perf_counter() - t0
            files = {f.path: f.content for f in result.files}
            report = review(task.role, files, contract)
            run.review_summary = report.summary()

            branch = f"kode/{feature_id[-6:]}/{task.role.value}"
            await github.create_branch(branch)
            name, email = agent.owner_name, agent.owner_email
            commit = await github.commit_files(
                branch, {**contract_files, **files},
                f"feat({task.role.value}): {task.title}\n\nContract sha256: {contract.sha256}\n"
                f"Generated by K.O.D.E. {task.role.value} agent for {name}.", name, email)
            await bus.publish(EventType.COMMIT, f"{task.role.value} committed {len(files)} files to {branch}", **rid,
                              data={"task_id": task.id, "sha": commit.sha, "branch": branch, "author": f"{name} <{email}>"})
            pr = await github.open_pr(
                branch, f"[K.O.D.E. {task.role.value}] {task.title}",
                f"{result.notes}\n\n**Owned files:** `{', '.join(task.files_owned)}`\n"
                f"**Frozen contract:** `{contract.sha256}`\n\n_Requires human approval before merge._")
            await bus.publish(EventType.PR_CREATED, f"{task.role.value} opened PR #{pr.number}", **rid,
                              data={"task_id": task.id, "url": pr.url, "number": pr.number})
            await github.comment(pr.number, report.markdown(contract.sha256))
            approval = ApprovalRequest(feature_id=feature_id, task_id=task.id, role=task.role, pr=pr,
                                       commit=commit, review_summary=report.summary())
            await state.save_approval(approval)
            await bus.publish(EventType.NEEDS_REVIEW, f"{task.role.value} PR #{pr.number} awaits human approval", **rid,
                              data={"task_id": task.id, "approval_id": approval.id, "url": pr.url,
                                    "review": report.summary()})
            task.status = TaskStatus.committed
            run.status, run.branch, run.commit_sha = "ok", branch, commit.sha
            run.author, run.pr_url, run.approval_id = f"{name} <{email}>", pr.url, approval.id
        except Exception as e:                      # one agent failing never cancels the others
            blocked = task.status == TaskStatus.blocked
            run.status, run.error = ("blocked" if blocked else "failed"), f"{type(e).__name__}: {e}"
            if not blocked:
                await bus.publish(EventType.BLOCKED, f"{task.role.value} agent failed: {e}", **rid,
                                  data={"task_id": task.id, "reason": type(e).__name__})
        finally:
            run.total_elapsed_s = time.perf_counter() - t0
            await state.save_task(task)
        return run

    start = time.perf_counter()
    runs = await asyncio.gather(*(run_one(t) for t in tasks))         # <- true concurrency
    wall = time.perf_counter() - start
    serial = sum(r.total_elapsed_s for r in runs)
    return DispatchReport(feature_id=feature_id, wall_s=wall, serial_s=serial,
                          speedup=(serial / wall) if wall else 1.0, runs=list(runs))


class ApprovalError(RuntimeError):
    pass


async def approve(approval_id: str, state: State, bus: EventBus, github: GitHubPort) -> ApprovalRequest:
    """The ONLY path to a merge."""
    a = await state.get_approval(approval_id)
    if not a:
        raise ApprovalError(f"unknown approval {approval_id}")
    if a.status != ApprovalStatus.pending:
        raise ApprovalError(f"approval {approval_id} is already {a.status.value}")
    a.status, a.decided_at = ApprovalStatus.approved, datetime.now(timezone.utc)
    await state.save_approval(a)
    try:
        a.merge_sha = await github.merge_pr(a)
    except Exception as e:
        a.status, a.reason = ApprovalStatus.pending, f"merge failed: {e}"
        await state.save_approval(a)
        raise ApprovalError(f"merge failed, approval returned to pending: {e}") from e
    a.status = ApprovalStatus.merged
    await state.save_approval(a)
    await bus.publish(EventType.COMMIT, f"PR #{a.pr.number} merged after human approval", feature_id=a.feature_id,
                      agent=a.role, data={"stage": "merge", "approval_id": a.id, "merge_sha": a.merge_sha})
    return a


async def reject(approval_id: str, reason: str, state: State, bus: EventBus, github: GitHubPort) -> ApprovalRequest:
    """Reject NEVER merges. It only closes the PR (best effort) and records the decision."""
    a = await state.get_approval(approval_id)
    if not a:
        raise ApprovalError(f"unknown approval {approval_id}")
    if a.status != ApprovalStatus.pending:
        raise ApprovalError(f"approval {approval_id} is already {a.status.value}")
    a.status, a.reason, a.decided_at = ApprovalStatus.rejected, reason or "no reason given", datetime.now(timezone.utc)
    await state.save_approval(a)
    try:
        await github.close_pr(a.pr.number, a.reason)
    except Exception:
        pass                                           # closing is cosmetic; the decision is recorded regardless
    await bus.publish(EventType.BLOCKED, f"PR #{a.pr.number} rejected by human: {a.reason}", feature_id=a.feature_id,
                      agent=a.role, data={"stage": "rejected", "approval_id": a.id})
    return a
